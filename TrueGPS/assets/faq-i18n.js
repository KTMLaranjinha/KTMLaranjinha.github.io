/* ==========================================================================
   Desenha a FAQ no <div id="faq-content"> e o título da secção.
   É chamada pelo app.js sempre que a língua muda (como o renderFeatures).
   ========================================================================== */
window.renderFaq = function (lang) {

  // Se o idioma não tiver FAQ, usa o inglês
  var dados = window.FAQ_T[lang] || window.FAQ_T.en;

  // Título da secção (ex.: "FAQ - Perguntas Frequentes")
  var titulo = document.querySelector('#faq > h2');
  if (titulo) titulo.textContent = dados.title;

  var caixa = document.getElementById('faq-content');
  if (!caixa) return;
  caixa.textContent = '';

  dados.items.forEach(function (item) {

    // Uma pergunta = um <details> (abre e fecha ao clicar)
    var bloco = document.createElement('details');

    var pergunta = document.createElement('summary');
    pergunta.textContent = item.q;
    bloco.appendChild(pergunta);

    // Resposta: texto simples = parágrafo; {list:[...]} = lista com marcas
    item.a.forEach(function (parte) {
      if (typeof parte === 'string') {
        var p = document.createElement('p');
        p.textContent = parte;
        bloco.appendChild(p);
      } else if (parte.list) {
        var ul = document.createElement('ul');
        parte.list.forEach(function (texto) {
          var li = document.createElement('li');
          li.textContent = texto;
          ul.appendChild(li);
        });
        bloco.appendChild(ul);
      }
    });

    caixa.appendChild(bloco);
  });
};
